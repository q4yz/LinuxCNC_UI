#: Basenames every generation writes into ``configs/``.
GENERATED_FILES = (
    "machine.cfg",
    "hardware.json",
    "machine.ini",
    "machine.hal",
    "custom.hal",
    "webgui_connections.hal",
    "postgui_call_list.hal",
    "tool.tbl",
)

#: The venv interpreter + machine backend entrypoint ``custom.hal``
#: loads as the ``webgui`` HAL userspace component. Both paths are
#: absolute (repo-root-relative), matching ``install.sh``'s venv
#: layout, so the generated INI works regardless of where LinuxCNC's
#: working directory ends up at boot.
_VENV_PYTHON = paths.PROJECT_ROOT / "backend" / "venv" / "bin" / "python"
_MACHINE_MAIN = paths.PROJECT_ROOT / "backend" / "machine" / "main.py"

MACHINE_HAL_HEADER = """\
# machine.hal - machine HAL: loads and connects the HAL components
# (MCU driver, motion, spindle, heaters, ...) of "{machine_name}".
#
# AUTO-GENERATED by the LinuxCNC_UI machine templates - do not edit.
# Every change here is overwritten when the machine is regenerated.
"""

CUSTOM_HAL_TEMPLATE = """\
# custom.hal - loads the "webgui" HAL component and sources
# webgui_connections.hal once it is up.
#
# AUTO-GENERATED by the LinuxCNC_UI machine templates - do not edit.
# Every change here is overwritten when the machine is regenerated.

# -W waits until the webgui component is ready before its pins are used
loadusr -W -n webgui {python} {main}

source webgui_connections.hal
"""

#: Written every time a machine is (re)generated — see the module
#: docstring. Machine-specific HAL wiring (spindle VFD, overrides,
#: ...) belongs here, not in ``custom.hal``. No longer preserved
#: across a regenerate: a confirmed override replaces it like every
#: other file, and the one machine that can't be overridden at all
#: (the current "main") is blocked before any file is touched — see
#: :class:`MainMachineProtectedError`.
WEBGUI_CONNECTIONS_HEADER = """\
# webgui_connections.hal - connects the UI ("webgui" component) to HAL.
# Sourced by custom.hal, runs after the webgui component is initialised.
#
# AUTO-GENERATED by the LinuxCNC_UI machine templates - do not edit.
# Every change here is overwritten when the machine is regenerated.
"""


def _render_webgui_connections_starter(payload: Dict[str, Any]) -> str:
    """The seed content written for ``webgui_connections.hal`` on
    every generation.

    ``render_webgui_connections`` (``services.halcompiler``) covers
    spindle + heater bindings today; anything it has no tool to bind
    (no spindle, no heater, or a different tool type entirely) simply
    adds nothing, so the header alone is exactly the static starter
    text.
    """
    bindings = render_webgui_connections(payload)
    if not bindings:
        return WEBGUI_CONNECTIONS_HEADER
    return WEBGUI_CONNECTIONS_HEADER + "\n" + bindings


POSTGUI_CALL_LIST_TEMPLATE = """\
# postgui_call_list.hal - HAL commands that run once the GUI has loaded.
#
# AUTO-GENERATED by the LinuxCNC_UI machine templates - do not edit.
# Every change here is overwritten when the machine is regenerated.
"""

#: Every tool number 1-99 is pre-registered with zeroed Z/D offsets.
#: LinuxCNC's ``io`` process treats a `T<n> M6` naming a tool absent
#: from this file as a hard error ("Requested tool not found") and
#: halts the program — but a hardware tool-length-setter workflow
#: measures the real offset live during the M6 macro (typically a
#: ``G10 L1`` overwriting this row in memory) rather than expecting
#: anyone to hand-type lengths here. Pre-registering the full range
#: means any tool number a program references resolves at parse time
#: regardless of which physical tools are actually loaded that day —
#: the table's only job is to exist and not reject a valid number.
#: Format verified against the real, working reference machine's own
#: table, ``machine_config/example/PrintNC-WEBGUI/tool.tbl``.
TOOL_TABLE_TEMPLATE = (
    "; tool.tbl - generated by the LinuxCNC_UI machine templates\n"
    "; Tools 1-99 pre-registered with Z/D zeroed for a dynamic\n"
    "; hardware tool-length-setter workflow -- offsets are measured\n"
    "; and applied live during the M6 macro (G10 L1), not hand-typed\n"
    "; here. Safe to leave as-is.\n"
    + "".join(
        f"T{n} P{n} Z0.0 D0.0 ; Auto-generated dummy tool\n" for n in range(1, 100)
    )
)


def _compile_machine(machine_name: str, payload: Dict[str, Any]) -> tuple[str, Dict[str, str]]:
    """The compiled wiring, or :class:`MachineInvalidError` — never a
    half-working machine.

    Returns ``(machine_hal_text, sidecar_files)`` — ``sidecar_files``
    maps a bare filename (``config_<mcu_id>.txt``, ``vfd_<mcu_id>.ini``
    — see :class:`.HalFragmentModels.HalFragment.files`) to its
    content, one entry per MCU that needed one. Keyed by MCU id, not a
    fixed name, precisely so a machine with two Remora boards gets
    ``config_mcu_a.txt`` *and* ``config_mcu_b.txt`` instead of the
    second one silently overwriting the first.

    Runs before any file is written: a machine that doesn't validate
    or assemble fails the whole generate (the router answers 422 with
    every diagnostic), and the existing machine folder stays as it was.
    """
    diagnostics = validate_machine(payload)
    if MachineValidator.has_errors(diagnostics):
        raise MachineInvalidError(machine_name, [d for d in diagnostics if d.is_error])

    try:
        fragment = assemble_machine(payload)
    except (UnsupportedMcuError, ValueError) as exc:
        raise MachineInvalidError(
            machine_name, [Diagnostic("E_COMPILE", Severity.ERROR, str(exc))]
        ) from exc

    hal_text = MACHINE_HAL_HEADER.format(machine_name=machine_name) + "\n" + render_hal(fragment)
    return hal_text, dict(fragment.files)


class MachineInvalidError(Exception):
    """Raised when a profile does not compile into a runnable machine.

    Attributes:
        machine: The machine name (= source file stem).
        diagnostics: Every error found — the operator fixes them in
            one pass.
    """

    def __init__(self, machine: str, diagnostics: List[Diagnostic]) -> None:
        self.machine = machine
        self.diagnostics = diagnostics
        super().__init__(
            f"Machine '{machine}' does not compile ({len(diagnostics)} error(s))."
        )


class MachineExistsError(Exception):
    """Raised when the target machine folder already exists.

    Attributes:
        machine: The machine name (= source file stem).
        existing_files: Relative paths currently on disk under the
            machine folder.
    """

    def __init__(self, machine: str, existing_files: List[str]) -> None:
        self.machine = machine
        self.existing_files = existing_files
        super().__init__(
            f"Machine '{machine}' already exists "
            f"({len(existing_files)} file(s)); pass confirm_override to replace it."
        )


class MainMachineProtectedError(Exception):
    """Raised when generate targets the currently-selected "main" machine.

    ``confirm_override`` lets an operator replace any *other* existing
    machine's whole folder — including ``webgui_connections.hal``,
    which is no longer spared (see the module docstring). The main
    machine is the one exception ``confirm_override`` cannot reach:
    it's whatever :meth:`MachineLifecycleService.default_machine`
    currently points at, i.e. the machine LinuxCNC would start next.
    Overriding it by clicking through a generic "replace?" warning is
    exactly the accidental-destruction case this blocks — deleting it
    on purpose first is an unambiguous, separate action.

    Attributes:
        machine: The protected machine's name.
    """

    def __init__(self, machine: str) -> None:
        self.machine = machine
        super().__init__(
            f"'{machine}' is the current main machine and cannot be "
            "overridden via generate. Delete it manually first, then "
            "regenerate."
        )


@dataclass(frozen=True)
class GenerateResult:
    """Outcome of one :func:`generate_machine_templates` run."""

    machine: str
    target_folder: str
    files: List[str] = field(default_factory=list)


def _posix(path: Path) -> str:
    return str(path).replace("\\", "/")


def _normalize_target(target_folder: str) -> str:
    """Normalize the optional target folder to a clean relative prefix."""
    parts = [p for p in (target_folder or "").replace("\\", "/").split("/") if p]
    if any(p in {".", ".."} for p in parts):
        raise ValueError(f"Invalid target folder: {target_folder!r}")
    return "/".join(parts)


def _machine_configs_relpath(machine_name: str, target_folder: str) -> str:
    prefix = f"{target_folder}/" if target_folder else ""
    return f"{prefix}{machine_name}/configs"


def resolve_machine_configs_dir(
    machine_service: MachineFileService, machine_path: str
) -> Path:
    """Resolve an operator-supplied ``machine_path`` to its ``configs/`` dir.

    Accepts either the machine's own folder (``"PrintNC"``) or the
    configs folder directly (``"PrintNC/configs"``) so callers don't
    need to know the internal ``configs/`` nesting convention. Used
    by the ``/deploy`` endpoint and :class:`MachineLifecycleService`
    to find what to copy into ``machine_config/active/``.

    Raises:
        ValueError: ``machine_path`` escapes ``machines/``.
    """
    target = machine_service.safe_join(machine_path)
    if target.is_dir() and target.name == "configs":
        return target
    return target / "configs"


def generate_machine_templates(
    profile_path: str,
    target_folder: str = "",
    confirm_override: bool = False,
    *,
    config_service: Optional[ConfigFileService] = None,
    machine_service: Optional[MachineFileService] = None,
    protected_machine: Optional[str] = None,
) -> GenerateResult:
    """Generate the template set for ``profile_path``.

    Args:
        profile_path: Path relative to ``profiles/``.
        target_folder: Optional folder under ``machines/`` to nest the
            machine folder in (supports operator grouping).
        confirm_override: Replace an existing machine folder without
            the existence check. Once set, *everything* under the
            machine folder is replaced — including
            ``webgui_connections.hal``, which used to survive a
            regenerate; see the module docstring.
        config_service: Override for tests (defaults to the factory).
        machine_service: Override for tests (defaults to the factory).
        protected_machine: The ``target_folder/machine_name`` of the
            currently-selected "main" machine (the router passes
            :meth:`MachineLifecycleService.default_machine`), or
            ``None`` when nothing is protected. When this generate call's
            own target matches it and the folder already exists, the
            call is refused regardless of ``confirm_override`` — see
            :class:`MainMachineProtectedError`.

    Raises:
        FileNotFoundError: The profile does not exist.
        ValueError: Path traversal or invalid target folder.
        MainMachineProtectedError: Target is the protected main machine.
        MachineExistsError: Target exists and ``confirm_override`` is false.
        MachineInvalidError: The profile does not compile; nothing is
            written.
    """
    config_service = config_service or ConfigFileService()
    machine_service = machine_service or MachineFileService()

    source = config_service.safe_join(profile_path)
    if not source.exists() or not source.is_file():
        raise FileNotFoundError(f"Profile not found: {profile_path}")

    machine_name = source.stem
    target_folder = _normalize_target(target_folder)
    configs_rel = _machine_configs_relpath(machine_name, target_folder)
    configs_dir = machine_service.safe_join(configs_rel)
    relative_name = f"{target_folder}/{machine_name}" if target_folder else machine_name

    if configs_dir.exists():
        # Checked before confirm_override, and blocks regardless of
        # it — accepting the generic "replace?" warning must not be
        # able to wipe the one machine actually in service.
        if protected_machine and relative_name == protected_machine:
            raise MainMachineProtectedError(relative_name)
        if not confirm_override:
            existing = sorted(
                str(p.relative_to(machine_service.root)).replace("\\", "/")
                for p in configs_dir.rglob("*")
                if p.is_file()
            )
            raise MachineExistsError(machine_name, existing)

    # Parse once, feed both the wire hardware.json AND the richer
    # in-memory Axis/Joint objects (which carry velocity/accel/scale/
    # home fields hardware.json doesn't serialise) to the INI
    # renderer. SPLIT_INTO_MULTIPLE_JOINTS (rather than the default
    # merge policy) is what makes a multi-motor axis — a dual-Y
    # gantry declared as ``[stepper_y]`` + ``[stepper_y1]`` — render
    # one [JOINT_N] per physical motor instead of collapsing them.
    graph = parse_config(source)
    payload: Dict[str, Any] = build_hardware_json(graph, machine_name)
    axes = AxisBuilder(graph, policy=AxisMappingPolicy.SPLIT_INTO_MULTIPLE_JOINTS).build()

    # Compiled before anything is touched: an invalid profile must not
    # replace a working machine with a broken one.
    hal_text, mcu_sidecar_files = _compile_machine(machine_name, payload)

    machine_service.clear_directory(configs_dir)

    # 1. Verbatim source copy (provenance).
    (configs_dir / "machine.cfg").write_bytes(source.read_bytes())

    # 2. The real runtime contract.
    (configs_dir / "hardware.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )

    # 3. The live INI — including PID sections for every PID heater
    # (machine.hal's `setp PID-<id>.KP [<SECTION>]PID_KP` lines are
    # ini-var references; without this they resolve to nothing).
    (configs_dir / "machine.ini").write_text(
        render_ini_template(machine_name, axes, payload.get("tools")), encoding="utf-8"
    )

    # 4. The real compiled wiring (motion/spindle/heaters), plus the
    # MCU sidecars (Remora config.txt, VFD serial .ini) compiled above.
    (configs_dir / "machine.hal").write_text(hal_text, encoding="utf-8")

    # 4b. One file per MCU that needed one — keyed by MCU id (see
    # module docstring) so a second Remora board never overwrites the
    # first board's config.txt.
    sidecar_files = [
        f"{configs_rel}/{filename}" for filename in sorted(mcu_sidecar_files)
    ]
    for filename, content in mcu_sidecar_files.items():
        (configs_dir / filename).write_text(content, encoding="utf-8")

    # 5. custom.hal always loads webgui and sources the file below —
    # regenerated every time so a repo-layout change (e.g. a venv
    # path change) is never stale.
    (configs_dir / "custom.hal").write_text(
        CUSTOM_HAL_TEMPLATE.format(python=_posix(_VENV_PYTHON), main=_posix(_MACHINE_MAIN)),
        encoding="utf-8",
    )

    # 6. webgui_connections.hal — seeded with real spindle/heater
    # bindings every time, like every other generated file (or, if
    # this machine declares neither, the static header alone). No
    # longer preserved across a regenerate — see the module docstring.
    (configs_dir / "webgui_connections.hal").write_text(
        _render_webgui_connections_starter(payload), encoding="utf-8"
    )

    # 7. Referenced by machine.ini but not part of the "artifacts a
    # profile drives" story — empty placeholders so LinuxCNC has
    # something to load.
    (configs_dir / "postgui_call_list.hal").write_text(
        POSTGUI_CALL_LIST_TEMPLATE, encoding="utf-8"
    )
    (configs_dir / "tool.tbl").write_text(TOOL_TABLE_TEMPLATE, encoding="utf-8")

    files = [
        f"{configs_rel}/{name}"
        for name in GENERATED_FILES
        if (configs_dir / name).exists()
    ] + sidecar_files
    logger.info(
        "Generated machine templates for '%s' under %s", machine_name, configs_rel
    )
    return GenerateResult(
        machine=machine_name, target_folder=target_folder, files=files
    )


