"""Template generation orchestrator.

Generates the per-machine template set from a profile ``.cfg``:

    profiles/<path>.cfg  ->  machines/<target_folder>/<stem>/configs/
                               machine.cfg              (verbatim source copy)
                               hardware.json             (real, existing generator)
                               machine.ini               (live INI — see ini_template_generator)
                               machine.hal               (real compiled wiring — see
                                                           _compile_machine)
                               config_<mcu_id>.txt       (Remora firmware payload, one per
                                                           Remora MCU)
                               vfd_<mcu_id>.ini          (VFD serial settings, one per
                                                           vfd_rs485 MCU)
                               custom.hal                (loads webgui, sources the file below)
                               webgui_connections.hal    (seeded with real spindle/heater bindings —
                                                           see _render_webgui_connections_starter)
                               postgui_call_list.hal     (empty placeholder; referenced by machine.ini)
                               tool.tbl                  (tools 1-99 pre-registered, Z/D zeroed —
                                                           see TOOL_TABLE_TEMPLATE)

The MCU sidecars (``config_<mcu_id>.txt``, ``vfd_<mcu_id>.ini``) are
keyed by MCU id, not a fixed name — a machine with two Remora boards
gets ``config_mcu_a.txt`` and ``config_mcu_b.txt``, never one file two
boards silently collide on. They are not in :data:`GENERATED_FILES` —
that list is the fixed files every generation writes; these are as
dynamic as the machine's own MCU list.

A profile that does not compile (validator errors, an unrouted MCU)
raises :class:`MachineInvalidError` before any file is written — the
router answers 422 with every diagnostic, never a 200 with a broken
``machine.hal``.

The machine name is the source file stem. When the target machine
folder already exists :class:`MachineExistsError` is raised unless
``confirm_override`` is set — the router translates that into a 409
the frontend confirms before retrying, and every file including
``webgui_connections.hal`` is regenerated from scratch (an operator
who clicked through "this will replace the existing configuration"
gets exactly that — no file is quietly spared, hand-wiring included).
The one machine a regenerate can never touch, confirmed or not, is
whichever one is currently selected as "main" (see
:class:`MainMachineProtectedError`) — that one has to be deleted by
hand first.
"""

