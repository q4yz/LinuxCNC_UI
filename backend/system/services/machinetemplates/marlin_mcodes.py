"""Marlin heater / fan M-codes for LinuxCNC (`.agent/component/gcode_upload.md` § 3).

LinuxCNC does not know ``M104`` (hotend), ``M109`` (hotend, wait),
``M140`` / ``M190`` (bed), ``M106`` / ``M107`` (fan). A machine with a
heater or fan gets them through the INI's ``REMAP``: each runs a small
subroutine (``subroutines/m104.ngc``) that calls a helper user M-code
(``mcodes/M180`` ... ``M182``, LinuxCNC runs those as programs and
waits until they exit):

* ``M180 P<°C> Q<heater>`` — set a heater's target (the machine
  backend's ``/tools/<id>/target``, the same the UI uses);
* ``M181 P<°C> Q<heater>`` — set it and wait until the sensor
  (``webgui.<sensor>``, read with ``halcmd getp``) is within
  :data:`WAIT_TOLERANCE_C` below the target (Marlin's ``M109 S``: wait
  while heating only);
* ``M182 P<0-255> Q<fan>`` — a part fan's speed (``/modules/io/<fan>``).

``Q`` is the extruder index (0 = first ``[extruder]``), ``-1`` the bed;
for fans the part-fan index. The heater and fan ids are written into the
helper when the machine is generated.

The remapped codes take ``P`` / ``Q``: an ``S`` word would also set the
spindle speed. Uploaded files are converted (``core.gcode_converter``:
``M104 S200 T1`` -> ``M104 P200 Q1``); type ``P`` in MDI and macros.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any

from mappers.machineconfig import PinStringMapper

#: Helper M-code numbers (user M-codes, ``mcodes/`` in the machine folder).
SET_TARGET, WAIT_TARGET, FAN_SPEED = 180, 181, 182
MCODES_DIR = "mcodes"
WAIT_TOLERANCE_C = 2.0
WAIT_TIMEOUT_S = 1800
MACHINE_BACKEND = "http://127.0.0.1:8000"


@dataclass(frozen=True)
class MarlinSupport:
    """What the generator writes for one machine."""

    remaps: list[str]               # [RS274NGC] REMAP= lines
    subroutines: dict[str, str]     # subroutines/<name> -> content
    mcodes: dict[str, str]          # mcodes/<name> -> executable content

    @property
    def enabled(self) -> bool:
        return bool(self.remaps)


def _heaters(payload: dict[str, Any]) -> tuple[list[list[str]], list[str] | None]:
    """``([[tool id, sensor id], ...] extruders, [tool id, sensor id] bed)``."""
    extruders, bed = [], None
    for tool in payload.get("tools") or []:
        if not isinstance(tool, dict):
            continue
        pair = [str(tool.get("id")), str(tool.get("sensor") or "")]
        if tool.get("type") == "extruder":
            extruders.append(pair)
        elif tool.get("type") == "heated_bed" and bed is None:
            bed = pair
    return extruders, bed


def _part_fans(payload: dict[str, Any]) -> list[str]:
    """Commandable part fans, in declaration order. A heater's placeholder
    fan shares the heater's own pin (listed in ``duplicate_pin_overrides``)
    and is skipped — driving it would drive the heater, the same rule
    ``render_webgui_connections`` applies."""
    shared = {str(p) for p in payload.get("duplicate_pin_overrides") or []}

    def on_shared_pin(fan: dict[str, Any]) -> bool:
        try:
            return PinStringMapper.from_string(str(fan.get("pin") or "")).qualified in shared
        except ValueError:
            return False

    return [
        str(f["id"]) for f in payload.get("fans") or []
        if isinstance(f, dict) and f.get("id") and f.get("kind", "part") == "part" and not on_shared_pin(f)
    ]


def _sub(name: str, body: list[str]) -> str:
    return "\n".join([
        f"; {name}.ngc - Marlin {name.upper()} for LinuxCNC (REMAP). AUTO-GENERATED - do not edit.",
        f"o<{name}> sub",
        *body,
        f"o<{name}> endsub",
        "M2",
        "",
    ])


def _param(var: str, word: str, default: str) -> list[str]:
    return [
        f"#<{var}> = {default}",
        f"o<{var}_{word}> if [EXISTS[#<{word}>]]",
        f"  #<{var}> = #<{word}>",
        f"o<{var}_{word}> endif",
    ]


_HELPER = '''#!/usr/bin/env python3
"""M{code} - {doc}

AUTO-GENERATED by the LinuxCNC_UI machine templates (marlin_mcodes.py):
regenerating the machine rewrites it. LinuxCNC runs it with P and Q as
the first two arguments and waits until it exits.
"""
import json
import subprocess
import sys
import time
import urllib.request

BACKEND = {backend!r}
EXTRUDERS = {extruders}
BED = {bed}
FANS = {fans}
MODE = {mode!r}
TOLERANCE = {tolerance!r}
TIMEOUT = {timeout!r}


def fail(message):
    print("M{code}: " + message, file=sys.stderr)
    sys.exit(1)


def request(method, path, body):
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(BACKEND + path, data=data, method=method,
                                 headers={{"Content-Type": "application/json"}})
    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            resp.read()
    except OSError as exc:
        fail("the machine backend did not take it (%s)" % exc)


def heater(index):
    index = int(round(index))
    if index < 0:
        if BED is None:
            fail("this machine has no heated bed")
        return BED
    if index >= len(EXTRUDERS):
        fail("this machine has no extruder %d" % index)
    return EXTRUDERS[index]


def actual(sensor):
    out = subprocess.run(["halcmd", "-s", "getp", "webgui." + sensor],
                         capture_output=True, text=True, timeout=5)
    try:
        return float(out.stdout.strip())
    except ValueError:
        fail("cannot read webgui.%s" % sensor)


def main(argv):
    p = float(argv[1]) if len(argv) > 1 else 0.0
    q = float(argv[2]) if len(argv) > 2 else 0.0
    if MODE == "fan":
        if not FANS:
            fail("this machine has no part fan")
        index = int(round(q))
        if not 0 <= index < len(FANS):
            fail("this machine has no fan %d" % index)
        request("PUT", "/api/v1/modules/io/" + FANS[index], {{"value": max(0.0, min(255.0, p)) / 255.0 * 100.0}})
        return 0
    tool, sensor = heater(q)
    request("POST", "/api/v1/modules/tools/tools/%s/target" % tool, {{"id": tool, "target": max(0.0, p)}})
    if MODE == "wait" and p > 0 and sensor:
        deadline = time.monotonic() + TIMEOUT
        while actual(sensor) < p - TOLERANCE:
            if time.monotonic() > deadline:
                fail("%s did not reach %.0f C in %d s" % (tool, p, TIMEOUT))
            time.sleep(1.0)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
'''


def marlin_support(payload: dict[str, Any]) -> MarlinSupport:
    """The REMAP lines, subroutines and helpers for ``payload`` — empty for
    a machine with neither a heater nor a part fan."""
    extruders, bed = _heaters(payload)
    fans = _part_fans(payload)
    remaps: list[str] = []
    subs: dict[str, str] = {}
    helpers: dict[str, str] = {}

    def helper(code: int, mode: str, doc: str) -> None:
        helpers[f"M{code}"] = _HELPER.format(
            code=code, doc=doc, backend=MACHINE_BACKEND, extruders=json.dumps(extruders),
            bed=json.dumps(bed) if bed else "None", fans=json.dumps(fans), mode=mode,
            tolerance=WAIT_TOLERANCE_C, timeout=WAIT_TIMEOUT_S,
        )

    if extruders or bed:
        helper(SET_TARGET, "set", "P<temperature> Q<heater>: set a heater's target (Q -1 = bed).")
        helper(WAIT_TARGET, "wait", "P<temperature> Q<heater>: set a heater's target and wait for it (Q -1 = bed).")
    if extruders:
        for name, code in (("m104", SET_TARGET), ("m109", WAIT_TARGET)):
            remaps.append(f"REMAP={name.upper()} modalgroup=10 argspec=pq ngc={name}")
            subs[f"{name}.ngc"] = _sub(name, _param("temp", "p", "0") + _param("heater", "q", "0")
                                       + [f"M{code} P#<temp> Q#<heater>"])
    if bed:
        for name, code in (("m140", SET_TARGET), ("m190", WAIT_TARGET)):
            remaps.append(f"REMAP={name.upper()} modalgroup=10 argspec=p ngc={name}")
            subs[f"{name}.ngc"] = _sub(name, _param("temp", "p", "0") + [f"M{code} P#<temp> Q-1"])
    if fans:
        helper(FAN_SPEED, "fan", "P<0-255> Q<fan>: set a part fan's speed.")
        remaps.append("REMAP=M106 modalgroup=10 argspec=pq ngc=m106")
        subs["m106.ngc"] = _sub("m106", _param("speed", "p", "255") + _param("fan", "q", "0")
                                + [f"M{FAN_SPEED} P#<speed> Q#<fan>"])
        remaps.append("REMAP=M107 modalgroup=10 argspec=q ngc=m107")
        subs["m107.ngc"] = _sub("m107", _param("fan", "q", "0") + [f"M{FAN_SPEED} P0 Q#<fan>"])
    return MarlinSupport(remaps=remaps, subroutines=subs, mcodes=helpers)


__all__ = ["FAN_SPEED", "MCODES_DIR", "SET_TARGET", "WAIT_TARGET", "MarlinSupport", "marlin_support"]
