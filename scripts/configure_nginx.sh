#!/bin/bash
# Write the LinuxCNC UI nginx site and (re)load nginx. Run as root.
#
#   sudo bash scripts/configure_nginx.sh            # from the repo root
#
# The site only carries what differs per installation (ports, TLS
# certificate, the built frontend's path); every route lives in the
# tracked deploy/nginx/linuxcnc-ui-routes.conf, which the site
# `include`s. So updates (git pull + nginx reload) pick up new routes
# without this script — it only has to run on install, and once on an
# installation from before the include existed (scripts/update.sh says
# so in its log and update status).
set -e

if [ "$(id -u)" -ne 0 ]; then
    echo "Error: run as root (sudo bash $0)" >&2
    exit 1
fi

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
UI_DIST_DIR="$PROJECT_DIR/frontend/dist"
# Same path install.sh / start_network.sh mint the mkcert certificate to.
CERT_DIR="$PROJECT_DIR/frontend/.cert"
ROUTES_FILE="$PROJECT_DIR/deploy/nginx/linuxcnc-ui-routes.conf"
NGINX_CONF="/etc/nginx/sites-available/linuxcnc-ui"

if [ ! -f "$ROUTES_FILE" ]; then
    echo "Error: $ROUTES_FILE is missing" >&2
    exit 1
fi

echo "---> Writing $NGINX_CONF (routes: $ROUTES_FILE)"
cat << EOF > "$NGINX_CONF"
# Generated by scripts/configure_nginx.sh — routes live in
# $ROUTES_FILE (tracked in git, applied on every update's nginx reload).

# HTTP Server (Port 80) - Used to show the Vue install popup
server {
    listen 80;
    server_name _;

    root $UI_DIST_DIR;
    index index.html;

    client_max_body_size 100M;

    # Ensure the .crt file triggers a download with the correct MIME type
    location = /cnc-root.crt {
        types { application/x-x509-ca-cert crt; }
        default_type application/x-x509-ca-cert;
        add_header Content-Disposition 'attachment; filename="cnc-root.crt"';
    }

    include $ROUTES_FILE;
}

# Application Server (Port 443 - HTTPS)
server {
    listen 443 ssl http2;
    server_name _;

    keepalive_timeout 75s;
    keepalive_requests 1000;

    ssl_certificate $CERT_DIR/localhost.pem;
    ssl_certificate_key $CERT_DIR/localhost-key.pem;

    root $UI_DIST_DIR;
    index index.html;

    client_max_body_size 100M;

    include $ROUTES_FILE;
}
EOF

ln -sf "$NGINX_CONF" /etc/nginx/sites-enabled/
rm -f /etc/nginx/sites-enabled/default

# Validate before touching the running server: a broken config must
# never take the UI down.
nginx -t
systemctl restart nginx
echo "---> nginx configured."
